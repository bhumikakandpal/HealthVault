import type { HealthRecord } from './types';

function formatDate(iso: string) {
  return new Date(iso).toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });
}

function slugify(text: string) {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function triggerBlobDownload(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function downloadRecord(record: HealthRecord) {
  // If we have the original file data (Base64), download it in its real format
  if (record.fileData) {
    const isDataUrl = record.fileData.startsWith('data:');
    if (isDataUrl) {
      // Convert data URL to Blob preserving the original MIME type
      const [header, base64] = record.fileData.split(',');
      const mimeMatch = header.match(/data:([^;]+)/);
      const mime = mimeMatch ? mimeMatch[1] : record.fileType || 'application/octet-stream';
      const byteString = atob(base64);
      const bytes = new Uint8Array(byteString.length);
      for (let i = 0; i < byteString.length; i++) {
        bytes[i] = byteString.charCodeAt(i);
      }
      const blob = new Blob([bytes], { type: mime });
      triggerBlobDownload(blob, record.fileName);
      return;
    }
  }

  // Fallback for dummy records (no file data): generate a text summary
  const lines: string[] = [
    'HealthVault — Medical Record',
    '============================',
    '',
    `Title:       ${record.title}`,
    `Category:    ${record.category}`,
    `Date:        ${formatDate(record.date)}`,
    `Doctor:      ${record.doctor}`,
    `Clinic:      ${record.clinic}`,
    `File:        ${record.fileName} (${record.fileSize})`,
    '',
    'Clinical Notes:',
    '---------------',
    record.notes,
    '',
  ];

  if (record.tags.length > 0) {
    lines.push(`Tags: ${record.tags.join(', ')}`, '');
  }

  lines.push(
    '---',
    `Generated by HealthVault on ${formatDate(new Date().toISOString())}`,
    'HealthVault is a personal organizer and does not provide medical diagnoses or replace clinical advice.',
  );

  const blob = new Blob([lines.join('\n')], { type: 'text/plain' });
  triggerBlobDownload(blob, `${slugify(record.title)}.txt`);
}

function escapeHtml(text: string) {
  const div = document.createElement('div');
  div.textContent = text;
  return div.innerHTML;
}

