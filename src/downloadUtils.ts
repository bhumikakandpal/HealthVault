export function downloadSummary(
  records: HealthRecord[],
  allergyRecords: HealthRecord[],
  staticAllergies: string[],
  patientName?: string,
  patientAge?: string,
  patientBloodGroup?: string,
) {
  const html = generateSummaryHtml(records, allergyRecords, staticAllergies, patientName, patientAge, patientBloodGroup);
  const blob = new Blob([html], { type: 'text/html' });
  triggerBlobDownload(blob, 'appointment-summary.html');
}

export function printSummary(
  records: HealthRecord[],
  allergyRecords: HealthRecord[],
  staticAllergies: string[],
  patientName?: string,
  patientAge?: string,
  patientBloodGroup?: string,
) {
  const html = generateSummaryHtml(records, allergyRecords, staticAllergies, patientName, patientAge, patientBloodGroup);
  const printWin = window.open('', '_blank', 'width=900,height=700');
  if (!printWin) {
    // Popup blocked — fall back to in-page print
    window.print();
    return;
  }
  printWin.document.open();
  printWin.document.write(html);
  printWin.document.close();
  // Wait for content to render before printing
  printWin.onload = () => {
    printWin.focus();
    printWin.print();
  };
}

export function downloadSummaryAsText(
  records: HealthRecord[],
  allergyRecords: HealthRecord[],
  staticAllergies: string[],
  patientName = 'Aman',
  patientAge = '21',
  patientBloodGroup = 'O+',
) {
  const lines: string[] = [
    'HealthVault — Appointment Summary',
    '=================================',
    '',
    'Patient Information',
    '-------------------',
    `Name:        ${patientName}`,
    `Age:         ${patientAge} years`,
    `Blood Group: ${patientBloodGroup}`,
    `Generated:   ${new Date().toLocaleDateString('en-US', { dateStyle: 'long' })}`,
    '',
    'Current Allergies',
    '-----------------',
  ];

  if (staticAllergies.length > 0) {
    staticAllergies.forEach((a) => lines.push(`  - ${a}`));
  } else {
    lines.push('  None on record');
  }

  if (allergyRecords.length > 0) {
    lines.push('');
    allergyRecords.forEach((rec) => {
      lines.push(`  ${rec.title}:`, `    ${rec.notes}`);
      if (rec.tags.length > 0) lines.push(`    Triggers: ${rec.tags.join(', ')}`);
      lines.push('');
    });
  }

  lines.push('', 'Medical History', '---------------');

  records.forEach((rec, idx) => {
    lines.push(
      '',
      `${idx + 1}. ${rec.title}`,
      `   Category: ${rec.category}`,
      `   Date:     ${formatDate(rec.date)}`,
      `   Doctor:   ${rec.doctor}`,
      `   Clinic:   ${rec.clinic}`,
      `   File:     ${rec.fileName}`,
      `   Notes:    ${rec.notes}`,
    );
    if (rec.tags.length > 0) {
      lines.push(`   Tags:     ${rec.tags.join(', ')}`);
    }
  });

  lines.push(
    '',
    '---',
    'This summary was generated by HealthVault. It is a personal organizer and does not',
    'provide medical diagnoses or replace clinical advice. Please consult your healthcare',
    'provider for medical guidance.',
  );

  const blob = new Blob([lines.join('\n')], { type: 'text/plain' });
  triggerBlobDownload(blob, 'appointment-summary.txt');
}
